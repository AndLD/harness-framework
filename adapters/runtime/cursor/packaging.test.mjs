import assert from 'node:assert/strict'
import { test } from 'node:test'
import { packageProcedure, skillPath } from './packaging.mjs'

const procedure = { name: 'start-it', description: 'Use when starting it.', invocation: 'explicit' }

test('a skill is a SKILL.md in a folder of its name under .cursor/skills, in native mode only', () => {
  assert.equal(skillPath(procedure, { adapters: { runtimes: ['cursor'] } }), '.cursor/skills/start-it/SKILL.md')
  assert.equal(skillPath(procedure), '.cursor/skills/start-it/SKILL.md')
  assert.equal(skillPath(procedure, { adapters: { runtimes: ['claude-code', 'cursor'] } }), undefined)
})

test('an explicit procedure is not chosen by the model, an automatic one is, and paths are kept', () => {
  assert.equal(
    packageProcedure(procedure, '# Start\n\n1. Go.\n\n\n'),
    '---\nname: start-it\ndescription: Use when starting it.\ndisable-model-invocation: true\n---\n\n<!-- Generated by `harness sync` from harness/core/procedures/start-it.md; do not edit this file. -->\n\n# Start\n\n1. Go.\n'
  )
  const auto = packageProcedure({ ...procedure, invocation: 'auto', paths: ['docs/**', 'core/**'] }, 'Body.')
  assert.doesNotMatch(auto, /disable-model-invocation/)
  assert.match(auto, /^---\nname: start-it\ndescription: Use when starting it\.\npaths: docs\/\*\*, core\/\*\*\n---\n/)
})
