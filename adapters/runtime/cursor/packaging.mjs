// The Cursor preset's packaging of the neutral procedures (design §8.1 and §9, role "procedure packaging"): in native mode each becomes the skill
// `.cursor/skills/<name>/SKILL.md`, with `name` and `description` in its frontmatter, and `disable-model-invocation: true` for an explicit one, so that it runs
// when invoked as `/<name>` and not on the model's own judgment. In compat mode Cursor loads the skills of `.claude/skills/`, and the preset writes none.
import { isCompat } from './mode.mjs'

/** The path of the skill for a procedure; undefined in compat mode. */
export const skillPath = (procedure, profile) =>
  isCompat(profile) ? undefined : `.cursor/skills/${procedure.name}/SKILL.md`

/** The text of the skill: the frontmatter, a note that it is generated, and the rendered body. */
export function packageProcedure(procedure, body) {
  const header = [
    '---',
    `name: ${procedure.name}`,
    `description: ${procedure.description}`,
    ...(procedure.invocation === 'explicit' ? ['disable-model-invocation: true'] : []),
    ...(procedure.paths ? [`paths: ${procedure.paths.join(', ')}`] : []),
    '---',
    '',
    `<!-- Generated by \`harness sync\` from harness/core/procedures/${procedure.name}.md; do not edit this file. -->`,
    ''
  ]
  return `${header.join('\n')}\n${body.replace(/\n+$/, '')}\n`
}
